import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { createClient } from 'genlayer-js';
import { studionet } from 'genlayer-js/chains';
import { TransactionHashVariant } from 'genlayer-js/types';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const release=JSON.parse(await readFile(resolve(root,'release.json'),'utf8'));
const source=await readFile(resolve(root,release.sourceFile));
const sha=b=>createHash('sha256').update(b).digest('hex');
const sort=v=>Array.isArray(v)?v.map(sort):v&&typeof v==='object'?Object.fromEntries(Object.keys(v).sort().map(k=>[k,sort(v[k])])):v;
const stable=v=>JSON.stringify(sort(v));
const parse=v=>typeof v==='string'?JSON.parse(v):v;
const fail=m=>{throw new Error(m)};
if(studionet.id!==61999)fail(`SDK chain ID changed: ${studionet.id}`);
if(sha(source)!==release.hash)fail('Checked-in source does not match pinned release SHA-256');
const client=createClient({chain:studionet}),address=release.address;
const code=await client.getContractCode(address);
if(sha(Buffer.from(code,'utf8'))!==release.hash)fail('RPC deployed source bytes do not match release source');
const localSchema=await client.getContractSchemaForCode(source);
const deployedSchema=await client.getContractSchema(address);
if(stable(localSchema)!==stable(deployedSchema))fail('Local ABI schema differs from deployed schema');
const abi=sha(Buffer.from(stable(localSchema),'utf8'));
if(abi!==release.abi)fail('ABI schema hash differs from the recorded V4 schema');
const read=async(name,args=[])=>client.readContract({address,functionName:name,args,transactionHashVariant:TransactionHashVariant.LATEST_FINAL});
const state=parse(await read('get_case',[release.case]));
const history=parse(await read('get_history',[release.case]));
if(state.id!==release.case||state.status!=='FINALIZED'||state.result!==release.verdict||state.round!==2||Number(state.finalized_at)<=0)fail('Canonical case state does not match preserved live result');
if(!Array.isArray(history)||history.length!==2||history.length!==state.round)fail('Canonical semantic history length is invalid');
let previous='';
for(let i=0;i<history.length;i++){const {entry_hash:claimed,...entry}=history[i];if(entry.prev!==previous||sha(Buffer.from(stable(entry),'utf8'))!==claimed)fail(`Canonical history SHA-256 link failed at entry ${i}`);previous=claimed;}
if(!Array.isArray(state.challenges)||state.challenges.length!==2)fail('Expected two authorized party challenge entries are absent');
async function verifyTx(hash,semantic){
 const tx=await client.getTransaction({hash});
 const phase=tx?.statusName??tx?.status_name, consensus=tx?.resultName??tx?.result_name;
 const leaders=tx?.consensus_data?.leader_receipt||[];
 const material=leaders.filter(x=>!(x.execution_result==='ERROR'&&/validator execution cancelled after quorum/i.test(String(x?.genvm_result?.stderr||x?.error||''))));
 const success=material.filter(x=>x.execution_result==='SUCCESS'), failed=material.filter(x=>x.execution_result!=='SUCCESS');
 const validators=tx?.consensus_data?.validators||[];
 if(phase!=='FINALIZED'||consensus!=='MAJORITY_AGREE'||!success.length||failed.length||!validators.length||(semantic&&tx?.txExecutionResultName&&tx.txExecutionResultName!=='FINISHED_WITH_RETURN'))fail(`Receipt check failed: status=${phase}, consensus=${consensus}, successful leader=${success.length}, failed leader=${failed.length}, validators=${validators.length}`);
 return {hash,phase,consensus,successfulLeaderExecutions:success.length,postQuorumCancellations:leaders.length-material.length,validatorCount:validators.length};
}
const receipts=[];
for(const hash of [release.firstRoundTx,release.secondRoundTx])receipts.push(await verifyTx(hash,true));
receipts.push(await verifyTx(release.finalizationTx,false));
const report={project:release.name,chainId:61999,address,sourceSha256:release.hash,abiSchemaSha256:abi,sourceParity:true,abiParity:true,caseId:state.id,status:state.status,verdict:state.result,round:state.round,challenges:state.challenges.length,historyEntries:history.length,historyHashChain:true,receipts,checkedAt:new Date().toISOString()};
const reportJson=JSON.stringify(report,null,2)+'\n';
await writeFile(resolve(root,'evidence','live-verification.json'),reportJson);
console.log(reportJson);
